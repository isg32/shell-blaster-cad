# Exports print-ready 3MF plates for several PETG / ASA material combinations.
# Run headless:  freecadcmd tools/export_3mf.py
# Output: 3mf/<variant>/<NN>_<material>_<colour>[_k].3mf  + 3mf/VARIANTS.md (plates + filament estimate)
# Every part keeps its print orientation and is a separate object (per-object settings in the slicer).
import os, shutil, runpy
import FreeCAD as App, Mesh, MeshPart
from FreeCAD import Vector as V

ROOT = '/home/isg32/dev/cad/glock-18-realistic-toy'
OUT = os.path.join(ROOT, '3mf')
BED, MARGIN, GAP = 256.0, 6.0, 8.0
DENSITY = {'PETG': 1.27, 'ASA': 1.07}          # g/cm3
FILL = 0.55                                     # rough: 4 walls + 30 % infill vs. a solid part

NS = runpy.run_path(os.path.join(ROOT, 'blaster.FCMacro'), run_name='export3mf')
NS['build_all']()

# role -> list of (part, copies, colour)
ROLES = {
    'frame':     [('Frame_R', 1, 'purple'), ('Frame_L', 1, 'purple')],
    'slide':     [('Slide', 1, 'black')],
    'accents':   [('Muzzle_Orange', 1, 'orange'), ('Trigger', 1, 'orange'), ('Mag_Release', 1, 'orange'),
                  ('Mag_Base', 1, 'orange')],
    'magazine':  [('Mag_Body', 1, 'purple'), ('Mag_Follower', 1, 'natural')],
    'internals': [('Bolt', 1, 'natural'), ('TubeCap', 1, 'natural'), ('Plunger_Head', 1, 'natural'),
                  ('Plunger_Rod', 1, 'natural'), ('Catch', 1, 'natural'), ('Trigger_Bar', 1, 'natural'),
                  ('Extractor', 3, 'natural'), ('Bolt_Peg', 2, 'natural')] +
                 [('Frame_Pin_%d' % k, 1, 'natural') for k in range(1, 8)],
    'springs':   [('Spring_Catch', 2, 'natural'), ('Spring_Trigger', 2, 'natural'), ('Spring_Release', 2, 'natural')],
    'shells':    [('Shell_Chambered', 10, 'any')],
}
P, A = 'PETG', 'ASA'
VARIANTS = [
    ('1_petg_main', 'Default: PETG everywhere except the ASA slide',
     {'frame': P, 'slide': A, 'accents': P, 'magazine': P, 'internals': P, 'shells': P, 'springs': P}),
    ('2_asa_internals_mag', 'ASA internals and magazine, PETG frame and accents, ASA slide',
     {'frame': P, 'slide': A, 'accents': P, 'magazine': A, 'internals': A, 'shells': P, 'springs': P}),
    ('3_asa_outside_petg_inside', 'ASA outside (frame, slide, accents), PETG internals, magazine and shells',
     {'frame': A, 'slide': A, 'accents': A, 'magazine': P, 'internals': P, 'shells': P, 'springs': P}),
    ('4_all_asa', 'Everything in ASA',
     {'frame': A, 'slide': A, 'accents': A, 'magazine': A, 'internals': A, 'shells': A, 'springs': P}),
    ('5_all_petg', 'Everything in PETG (no enclosure needed)',
     {'frame': P, 'slide': P, 'accents': P, 'magazine': P, 'internals': P, 'shells': P, 'springs': P}),
]
NOTES = {
    'ASA': 'ASA: enclosure closed, ~260 C / 100 C bed, no fan for the first layers; turn on the slicer\'s '
           'filament shrinkage compensation (~0.5-0.7 %) or the 0.3 mm sliding fits get tight.',
    'flex_ASA': 'Extractor / mag base snaps in ASA are stiffer and more brittle than PETG: print the spare '
                'extractors, and if one cracks print it in PETG. The printed springs are always PETG (or TPU).',
}


def mesh_of(shape):
    return MeshPart.meshFromShape(Shape=shape, LinearDeflection=0.03, AngularDeflection=0.25, Relative=False)


def pack(items):
    """shelf packing onto as many 256 mm plates as needed. items: [(label, shape)] -> [[(label, shape)], ...]"""
    items = sorted(items, key=lambda t: -max(t[1].BoundBox.XLength, t[1].BoundBox.YLength))
    plates, cur, x, y, row_h = [], [], MARGIN, MARGIN, 0.0
    for label, sh in items:
        bb = sh.BoundBox
        if bb.XLength < bb.YLength and bb.YLength <= BED - 2 * MARGIN:
            sh = sh.copy(); sh.rotate(V(0, 0, 0), V(0, 0, 1), 90); bb = sh.BoundBox
        if x + bb.XLength > BED - MARGIN:
            x, y, row_h = MARGIN, y + row_h + GAP, 0.0
        if y + bb.YLength > BED - MARGIN:                  # start a new plate
            plates.append(cur)
            cur, x, y, row_h = [], MARGIN, MARGIN, 0.0
        cur.append((label, sh.translated(V(x - bb.XMin, y - bb.YMin, -bb.ZMin))))
        x += bb.XLength + GAP
        row_h = max(row_h, bb.YLength)
    if cur:
        plates.append(cur)
    return plates


def write_plate(path, placed):
    doc = App.newDocument('P')
    objs = []
    for label, sh in placed:
        o = doc.addObject('Mesh::Feature', label)
        o.Mesh = mesh_of(sh)
        o.Label = label
        objs.append(o)
    Mesh.export(objs, path)
    ok = all(o.Mesh.isSolid() for o in objs)
    App.closeDocument('P')
    return ok


if os.path.isdir(OUT):
    shutil.rmtree(OUT)
os.makedirs(OUT)
md = ['# Material variants', '',
      'Generated by `tools/export_3mf.py`. Each folder holds ready-to-print 3MF plates (256 x 256 bed),',
      'one or more per filament + colour. Filament weights are rough estimates (4 walls, 30 % infill).', '']
summary = []
for vname, desc, mats in VARIANTS:
    vdir = os.path.join(OUT, vname)
    os.makedirs(vdir)
    groups = {}
    for role, parts in ROLES.items():
        mat = mats[role]
        for name, n, col in parts:
            key = (mat, col, 'fine' if role == 'shells' else 'springs' if role == 'springs' else '')
            sh = NS['print_shape'](name)
            for k in range(n):
                groups.setdefault(key, []).append(('%s_%d' % (name, k + 1) if n > 1 else name, sh))
    rows, grams = [], {'PETG': 0.0, 'ASA': 0.0}
    idx = 1
    for key in sorted(groups, key=lambda k: (k[0], k[1], k[2])):
        mat, col, tag = key
        plates = pack(groups[key])
        for k, placed in enumerate(plates):
            fname = '%02d_%s_%s%s%s.3mf' % (idx, mat, col, '_fine_layers' if tag == 'fine' else '_springs' if tag else '', '_%d' % (k + 1) if len(plates) > 1 else '')
            ok = write_plate(os.path.join(vdir, fname), placed)
            g = sum(s.Volume for _, s in placed) / 1000.0 * DENSITY[mat] * FILL
            grams[mat] += g
            rows.append('| `%s` | %s %s | %s | ~%.0f g | %s |' % (
                fname, mat, col, ', '.join(l for l, _ in placed), g, 'yes' if ok else 'NO'))
            idx += 1
    md += ['## %s' % vname, '', desc + '.', '',
           '| Plate | Filament | Parts | Filament | Closed mesh |', '|---|---|---|---|---|'] + rows + ['']
    tot = ', '.join('%s ~%.0f g' % (m, g) for m, g in grams.items() if g > 0)
    md += ['**Total:** ' + tot + '.', '']
    if any(m == 'ASA' for m in mats.values()):
        md += ['> ' + NOTES['ASA']]
    if mats['internals'] == 'ASA' or mats['accents'] == 'ASA':
        md += ['> ' + NOTES['flex_ASA']]
    md += ['']
    summary.append('%-28s %2d plates  %s' % (vname, len(rows), tot))
open(os.path.join(OUT, 'VARIANTS.md'), 'w').write('\n'.join(md))
print('\n'.join(summary))
